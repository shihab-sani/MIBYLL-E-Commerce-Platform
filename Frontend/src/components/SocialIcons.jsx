export default function SocialIcons({ links = [] }) {
    if (!links.length) return null

    return (
        <div className="flex flex-wrap items-center gap-4">
            {links.map((l, i) => {
                const preset = PRESET_PATHS[l.platform]
                const Wrapper = l.url ? 'a' : 'div'
                const props = l.url
                    ? { href: l.url, target: '_blank', rel: 'noopener noreferrer' }
                    : {}

                return (
                    <Wrapper
                        key={i}
                        {...props}
                        aria-label={l.label || l.platform}
                        title={l.label || l.platform}
                        className="w-6 h-6 flex items-center justify-center
                                   text-neutral-400 hover:text-white transition-colors"
                    >
                        {preset ? (
                            <svg viewBox="0 0 24 24" fill="currentColor" className="w-full h-full">
                                <path d={preset} />
                            </svg>
                        ) : l.iconUrl ? (
                            <img src={l.iconUrl} alt="" className="w-full h-full object-contain" />
                        ) : null}
                    </Wrapper>
                )
            })}
        </div>
    )
}
